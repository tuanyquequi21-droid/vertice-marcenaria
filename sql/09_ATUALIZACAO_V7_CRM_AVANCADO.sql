-- CPF único por empresa (idempotente; pressupõe duplicidades antigas já saneadas).
update public.clientes set cpf_normalizado=nullif(regexp_replace(coalesce(cpf,''),'\D','','g'),'');
create or replace function public.normalizar_cpf_cliente() returns trigger language plpgsql set search_path=public as $$
begin new.cpf_normalizado:=nullif(regexp_replace(coalesce(new.cpf,''),'\D','','g'),''); return new; end; $$;
drop trigger if exists trg_normalizar_cpf_cliente on public.clientes;
create trigger trg_normalizar_cpf_cliente before insert or update of cpf on public.clientes for each row execute function public.normalizar_cpf_cliente();
create unique index if not exists clientes_empresa_cpf_unique on public.clientes(empresa_id,cpf_normalizado) where cpf_normalizado is not null and cpf_normalizado<>'';

-- RLS padrão por empresa.
do $$ declare t text; begin
 foreach t in array array['cliente_documentos','mensagens_modelo','automacoes_crm','orcamento_versoes','orcamento_opcoes','pos_venda'] loop
  execute format('alter table public.%I enable row level security',t);
  execute format('drop policy if exists %I on public.%I',t||'_sel',t);
  execute format('drop policy if exists %I on public.%I',t||'_ins',t);
  execute format('drop policy if exists %I on public.%I',t||'_upd',t);
  execute format('drop policy if exists %I on public.%I',t||'_del',t);
  execute format('create policy %I on public.%I for select to authenticated using(empresa_id=public.minha_empresa())',t||'_sel',t);
  execute format('create policy %I on public.%I for insert to authenticated with check(empresa_id=public.minha_empresa())',t||'_ins',t);
  execute format('create policy %I on public.%I for update to authenticated using(empresa_id=public.minha_empresa()) with check(empresa_id=public.minha_empresa())',t||'_upd',t);
  execute format('create policy %I on public.%I for delete to authenticated using(empresa_id=public.minha_empresa())',t||'_del',t);
  execute format('drop trigger if exists %I on public.%I','trg_empresa_'||t,t);
  execute format('create trigger %I before insert on public.%I for each row execute function public.set_empresa_id()','trg_empresa_'||t,t);
 end loop;
end $$;

