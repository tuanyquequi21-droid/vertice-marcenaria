create or replace function public.get_proposta_publica(p_token uuid)
returns jsonb language sql security definer set search_path=public as $$
 select jsonb_build_object('id',o.id,'cliente_nome',o.cliente_nome,'projeto',o.projeto,'preco_final',o.preco_final,
 'forma_pagamento',o.forma_pagamento,'numero_parcelas',o.numero_parcelas,'prazo_entrega_dias',o.prazo_entrega_dias,
 'validade_dias',o.validade_dias,'observacoes_cliente',o.observacoes_cliente,'status',o.status,'aceite_em',o.aceite_em,
 'opcoes',coalesce((select jsonb_agg(jsonb_build_object('nome',x.nome,'descricao',x.descricao,'valor',x.valor,'destaque',x.destaque) order by x.ordem) from public.orcamento_opcoes x where x.orcamento_id=o.id),'[]'::jsonb))
 from public.orcamentos o where o.public_token=p_token limit 1;
$$;
