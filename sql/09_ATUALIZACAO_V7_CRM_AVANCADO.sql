returns boolean language plpgsql security definer set search_path=public as $$
begin
 update public.orcamentos set status='Aprovado',aprovado_em=now(),aceite_em=now(),aceite_nome=left(coalesce(p_nome,''),150) where public_token=p_token and coalesce(status,'') not in ('Recusado','Cancelado');
 return found;
end; $$;
grant execute on function public.get_proposta_publica(uuid) to anon,authenticated;
