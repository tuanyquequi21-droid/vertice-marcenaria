-- Garante que o trigger funciona no SQL Editor quando empresa_id já é informado.
create or replace function public.set_empresa_id()
returns trigger language plpgsql security definer set search_path=public as $$
declare v_empresa uuid;
begin
  if new.empresa_id is not null then return new; end if;
  v_empresa:=public.minha_empresa();
  if v_empresa is null then raise exception 'Usuário sem empresa ativa'; end if;
  new.empresa_id:=v_empresa; return new;
end; $$;

create table if not exists public.funcionarios(
 id bigint generated by default as identity primary key,
 empresa_id uuid not null references public.empresas(id) on delete cascade,
 nome text not null,
 funcao_id bigint references public.mao_obra_funcoes(id) on delete set null,
 telefone text,
 observacoes text,
 ativo boolean not null default true,
 criado_em timestamptz not null default now()
);
alter table public.orcamento_mao_obra add column if not exists funcionario_id bigint references public.funcionarios(id) on delete set null;
alter table public.orcamento_mao_obra add column if not exists funcionario_nome text;

-- Compatibilidade definitiva com a tabela antiga.
alter table public.orcamento_itens alter column tipo set default 'Material';
alter table public.orcamento_itens alter column descricao set default 'Material';
update public.orcamento_itens set tipo=coalesce(tipo,'Material'),
 descricao=coalesce(nullif(descricao,''),nullif(nome_material,''),'Material')
where tipo is null or descricao is null or descricao='';

-- Financeiro: preserva tabela existente; cria/adiciona somente o que faltar.
create table if not exists public.transacoes(
 id bigint generated by default as identity primary key,
 empresa_id uuid references public.empresas(id) on delete cascade,
 tipo text not null default 'Entrada',
 descricao text,
 categoria text,
 valor numeric(12,2) default 0,
 valor_total numeric(12,2) default 0,
 data date default current_date,
 data_inicial date,
 recorrencia text default 'Único',
 parcelas integer default 1,
 status text default 'Pendente',
 criado_em timestamptz not null default now()
);
alter table public.transacoes add column if not exists empresa_id uuid references public.empresas(id) on delete cascade;
alter table public.transacoes add column if not exists valor numeric(12,2) default 0;
alter table public.transacoes add column if not exists valor_total numeric(12,2) default 0;
alter table public.transacoes add column if not exists data date;
alter table public.transacoes add column if not exists data_inicial date;
alter table public.transacoes add column if not exists recorrencia text default 'Único';
alter table public.transacoes add column if not exists parcelas integer default 1;

alter table public.funcionarios enable row level security;
drop policy if exists funcionarios_select on public.funcionarios;
drop policy if exists funcionarios_insert on public.funcionarios;
drop policy if exists funcionarios_update on public.funcionarios;
drop policy if exists funcionarios_delete on public.funcionarios;
create policy funcionarios_select on public.funcionarios for select to authenticated using(empresa_id=public.minha_empresa());
create policy funcionarios_insert on public.funcionarios for insert to authenticated with check(empresa_id=public.minha_empresa());
create policy funcionarios_update on public.funcionarios for update to authenticated using(empresa_id=public.minha_empresa()) with check(empresa_id=public.minha_empresa());
create policy funcionarios_delete on public.funcionarios for delete to authenticated using(empresa_id=public.minha_empresa());
drop trigger if exists trg_empresa_funcionarios on public.funcionarios;
create trigger trg_empresa_funcionarios before insert on public.funcionarios for each row execute function public.set_empresa_id();

-- Aplica RLS de empresa ao financeiro apenas quando empresa_id está disponível.
alter table public.transacoes enable row level security;
drop policy if exists transacoes_select_v6 on public.transacoes;
drop policy if exists transacoes_insert_v6 on public.transacoes;
drop policy if exists transacoes_update_v6 on public.transacoes;
drop policy if exists transacoes_delete_v6 on public.transacoes;
create policy transacoes_select_v6 on public.transacoes for select to authenticated using(empresa_id=public.minha_empresa());
create policy transacoes_insert_v6 on public.transacoes for insert to authenticated with check(empresa_id=public.minha_empresa());
create policy transacoes_update_v6 on public.transacoes for update to authenticated using(empresa_id=public.minha_empresa()) with check(empresa_id=public.minha_empresa());
create policy transacoes_delete_v6 on public.transacoes for delete to authenticated using(empresa_id=public.minha_empresa());
drop trigger if exists trg_empresa_transacoes_v6 on public.transacoes;
create trigger trg_empresa_transacoes_v6 before insert on public.transacoes for each row execute function public.set_empresa_id();

grant select,insert,update,delete on public.funcionarios,public.transacoes to authenticated;
grant usage,select on all sequences in schema public to authenticated;
