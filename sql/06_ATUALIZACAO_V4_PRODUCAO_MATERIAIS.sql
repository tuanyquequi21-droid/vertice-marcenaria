-- Materiais: amplia MDF/ferragens e cria catálogo genérico.
create table if not exists public.materiais (
  id bigint generated by default as identity primary key,
  empresa_id uuid not null references public.empresas(id) on delete cascade,
  categoria text not null default 'Outros',
  nome text not null,
  marca text,
  fornecedor text,
  unidade text not null default 'unidade',
  preco_custo numeric(12,2) not null default 0,
  estoque_atual numeric(12,3) default 0,
  estoque_minimo numeric(12,3) default 0,
  observacoes text,
  ativo boolean not null default true,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);

create table if not exists public.producao (
  id bigint generated by default as identity primary key,
  empresa_id uuid not null references public.empresas(id) on delete cascade,
  orcamento_id bigint references public.orcamentos(id) on delete set null,
  cliente_id bigint references public.clientes(id) on delete set null,
  lead_id bigint references public.crm_leads(id) on delete set null,
  cliente_nome text not null,
  projeto text not null,
  status text not null default 'Aguardando produção'
    check (status in ('Aguardando produção','Em fabricação','Aguardando montagem','Montagem agendada','Concluído','Pausado')),
  inicio_previsto date,
  inicio_real date,
  dias_fabricacao numeric(8,2) default 0,
  conclusao_prevista date,
  conclusao_real date,
  montagem_prevista date,
  entrega_prevista date,
  responsavel text,
  observacoes text,
  criado_por uuid default auth.uid(),
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);

create index if not exists idx_materiais_empresa on public.materiais(empresa_id,categoria,ativo);
create index if not exists idx_producao_empresa_status on public.producao(empresa_id,status,inicio_previsto);

alter table public.materiais enable row level security;
alter table public.producao enable row level security;

grant select,insert,update,delete on public.materiais to authenticated;
grant select,insert,update,delete on public.producao to authenticated;
grant usage,select on all sequences in schema public to authenticated;

drop policy if exists materiais_select on public.materiais;
drop policy if exists materiais_insert on public.materiais;
drop policy if exists materiais_update on public.materiais;
drop policy if exists materiais_delete on public.materiais;
create policy materiais_select on public.materiais for select to authenticated using(empresa_id=public.minha_empresa());
create policy materiais_insert on public.materiais for insert to authenticated with check(empresa_id=public.minha_empresa());
create policy materiais_update on public.materiais for update to authenticated using(empresa_id=public.minha_empresa()) with check(empresa_id=public.minha_empresa());
create policy materiais_delete on public.materiais for delete to authenticated using(empresa_id=public.minha_empresa());

drop policy if exists producao_select on public.producao;
drop policy if exists producao_insert on public.producao;
drop policy if exists producao_update on public.producao;
drop policy if exists producao_delete on public.producao;
create policy producao_select on public.producao for select to authenticated using(empresa_id=public.minha_empresa());
create policy producao_insert on public.producao for insert to authenticated with check(empresa_id=public.minha_empresa());
create policy producao_update on public.producao for update to authenticated using(empresa_id=public.minha_empresa()) with check(empresa_id=public.minha_empresa());
create policy producao_delete on public.producao for delete to authenticated using(empresa_id=public.minha_empresa());

-- Trigger empresa_id para as novas tabelas.
drop trigger if exists trg_empresa_materiais on public.materiais;
create trigger trg_empresa_materiais before insert on public.materiais
for each row execute function public.set_empresa_id();

drop trigger if exists trg_empresa_producao on public.producao;
create trigger trg_empresa_producao before insert on public.producao
for each row execute function public.set_empresa_id();

-- Atualização automática de timestamp.
create or replace function public.touch_updated_at()
returns trigger language plpgsql as $$
begin new.atualizado_em=now(); return new; end $$;

drop trigger if exists trg_touch_materiais on public.materiais;
create trigger trg_touch_materiais before update on public.materiais
for each row execute function public.touch_updated_at();

drop trigger if exists trg_touch_producao on public.producao;
create trigger trg_touch_producao before update on public.producao
for each row execute function public.touch_updated_at();

-- Permite exclusão de orçamento da própria empresa.
drop policy if exists orcamentos_delete on public.orcamentos;
create policy orcamentos_delete on public.orcamentos
for delete to authenticated using(empresa_id=public.minha_empresa());
